describe('Calendar Ops workspace',()=>{
  it('creates role-bound accounts, schedules a lesson, and shows a mobile student calendar',()=>{
    const api=(path,body)=>cy.request({method:'POST',url:'/api/v1/'+path,body,headers:{Origin:'http://127.0.0.1:4173','X-Calendar-Client':'1'}})
    cy.viewport(1440,900)
    cy.visit('/')
    cy.get('input[name=username]').type('owner')
    cy.get('input[name=password]').type('local-browser-test-password',{log:false})
    cy.contains('button','Войти').click()
    cy.contains('h1','Расписание').should('be.visible')
    cy.get('.metrics').should('not.exist')
    cy.contains('button','Тёмная').click()
    cy.get('html').should('have.attr','data-theme','dark')
    cy.contains('button','Светлая').click()
    cy.get('.sx__calendar-wrapper').should('exist')
    api('invites',{role:'tutor'}).then(({body})=>cy.wrap(body.code,{log:false}).as('tutorCode'))
    api('invites',{role:'student'}).then(({body})=>cy.wrap(body.code,{log:false}).as('studentCode'))
    cy.contains('button','Выйти').click()
    cy.contains('button','У меня есть код').click()
    cy.get('input[name=name]').type('Репетитор')
    cy.get('@tutorCode').then(code=>cy.get('input[name=code]').type(code,{log:false}))
    cy.get('input[name=username]').type('tutor-browser')
    cy.get('input[name=password]').type('test-password-long',{log:false})
    cy.contains('button','Создать аккаунт').click()
    cy.contains('h1','Расписание').should('be.visible')
    cy.contains('button','+ Занятие').should('be.visible')
    cy.contains('button','Доступность').click()
    cy.contains('button','+ Интервал').click()
    cy.get('dialog input[name=start]').clear().type('2026-12-01T09:00')
    cy.get('dialog input[name=end]').clear().type('2026-12-01T12:00')
    cy.contains('button','Сохранить доступность').click()
    cy.get('dialog').should('not.exist')
    cy.get('.availability-row').should('contain','09:00')
    cy.contains('button','Выйти').click()
    cy.get('@studentCode').then(code=>api('register',{username:'student-browser',name:'Ученик',password:'test-password-long',code}))
    api('logout',{})
    api('login',{username:'owner',password:'local-browser-test-password'})
    cy.visit('/')
    cy.contains('button','+ Занятие').click()
    cy.get('dialog input[name=title]').type('Математика')
    cy.get('dialog select[name=duration_preset]').should('have.value','60')
    cy.get('dialog select[name=payment_status]').should('have.value','unpaid')
    cy.get('dialog input[name=start]').clear().type('2026-12-01T10:00')
    cy.get('dialog input[name=end]').clear().type('2026-12-01T11:00')
    cy.contains('button','Сохранить').click()
    cy.get('dialog').should('not.exist')
    cy.contains('button','Доска').click()
    cy.contains('.lesson','Математика').should('be.visible').and('have.class','status-tentative').and('have.css','border-top-style','dashed')
    cy.get('select[name=student_filter]').select('Ученик')
    cy.contains('.lesson','Математика').should('be.visible').click()
    cy.get('dialog select[name=status]').select('confirmed')
    cy.get('dialog select[name=payment_status]').select('paid')
    cy.get('dialog input[name=receipt_received]').check()
    cy.contains('button','Сохранить').click()
    cy.get('dialog').should('not.exist')
    cy.contains('.lesson','Математика').should('have.class','status-confirmed')
    cy.get('select[name=status_filter]').select('tentative')
    cy.contains('.lesson','Математика').should('not.exist')
    cy.get('select[name=status_filter]').select('confirmed')
    cy.contains('.lesson','Математика').should('be.visible')
    cy.contains('.lesson','Математика').find('.payment-badge').should('contain','Оплачено')
    cy.get('select[name=tutor_filter]').select('Репетитор')
    cy.contains('button','Доступность').click()
    cy.get('.availability-row').should('have.length',2)
    cy.get('select[name=payment_filter]').select('unpaid')
    cy.contains('.lesson','Математика').should('not.exist')
    cy.contains('button','Сбросить').click()
    cy.contains('button','+ Занятие').click()
    cy.get('dialog input[name=title]').type('Знакомство')
    cy.get('dialog input[name=start]').clear().type('2026-12-01T11:00')
    cy.get('dialog select[name=lesson_type]').select('trial')
    cy.get('dialog select[name=duration_preset]').should('have.value','30')
    cy.get('dialog input[name=end]').should('have.value','2026-12-01T11:30')
    cy.contains('button','Сохранить').click()
    cy.get('dialog').should('not.exist')
    cy.contains('.lesson','Знакомство').should('have.class','type-trial').and('have.css','background-color','rgb(237, 233, 254)').and('have.css','border-top-style','dashed')
    cy.get('select[name=type_filter]').select('trial')
    cy.contains('.lesson','Математика').should('not.exist')
    cy.contains('button','Сбросить').click()
    cy.screenshot('admin-board')
    cy.contains('button','Выйти').click()
    api('login',{username:'tutor-browser',password:'test-password-long'})
    cy.visit('/')
    cy.contains('h1','Расписание').should('be.visible')
    cy.contains('button','Доска').click()
    cy.contains('.lesson','Знакомство').click()
    cy.get('dialog select[name=payment_status]').select('paid')
    cy.contains('button','Сохранить').click()
    cy.get('dialog').should('not.exist')
    cy.contains('.lesson','Знакомство').find('.payment-badge').should('contain','Оплачено')
    cy.contains('button','Выйти').click()
    api('login',{username:'student-browser',password:'test-password-long'})
    cy.viewport(390,844)
    cy.visit('/')
    cy.contains('h1','Расписание').should('be.visible')
    cy.contains('button','Доска').click()
    cy.contains('.lesson','Математика').should('be.visible')
    cy.contains('button','+ Занятие').should('not.exist')
    cy.contains('.lesson','Математика').click()
    cy.get('dialog').should('contain','Подтверждено').and('contain','Ученик').and('contain','Оплачено').and('contain','Получен')
    cy.get('dialog select[name=payment_status]').should('not.exist')
    cy.contains('button','Закрыть',{matchCase:true}).click()
    cy.document().then(doc=>expect(doc.documentElement.scrollWidth).to.be.lte(391))
    cy.screenshot('student-mobile')
    cy.visit('/calendar')
    cy.get('.sx__calendar-wrapper').should('exist')
    cy.get('.sidebar').should('not.exist')
    cy.document().then(doc=>expect(doc.documentElement.scrollWidth).to.be.lte(391))
  })
})
